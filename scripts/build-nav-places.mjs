// Builds the airport and port gazetteers the server names flight and ship
// events with: server/src/data/airports.ts and server/src/data/ports.ts.
//
//   npm i --no-save all-the-cities@3.1.0
//   npm run build:nav-places
//
// Sources (downloaded on each run):
//   - Airports: OurAirports (public domain), https://ourairports.com/data/ —
//     open airports with a runway of at least 4,000 ft, the field length the
//     company jets need, so a takeoff names the airport and not a grass strip
//     beside it.
//   - Ports: UN/LOCODE (UNECE) locations coded as ports, via the
//     datasets/un-locode mirror (unece.org itself sits behind a bot check).
//     About a fifth of UN/LOCODE ports carry no coordinates; those take the
//     coordinates of the same-named GeoNames town in the same country
//     (all-the-cities, CC BY 4.0, geonames.org).
//   - Windstar's own ports of call (below): tender anchorages and bays the
//     gazetteers don't name, preferred within range.
//
// Output rows are tab-separated in a template literal, parsed on first use
// (server/src/navPlaces.ts), the same packing client/src/layers/ships/
// majorCities.ts uses.

