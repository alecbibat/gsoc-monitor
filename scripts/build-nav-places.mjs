async function fetchText(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.text();
}

// RFC 4180-ish: quoted fields, doubled quotes, CRLF tolerated.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let f = '';
  let q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"') {
        if (text[i + 1] === '"') { f += '"'; i++; } else q = false;
      } else f += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { row.push(f); f = ''; }
    else if (ch === '\n') { row.push(f); rows.push(row); row = []; f = ''; }
    else if (ch !== '\r') f += ch;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  const head = rows.shift();
  return rows.filter((r) => r.length === head.length).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

/** A field safe inside a tab-separated row inside a template literal. */
function field(v) {
  return String(v ?? '').replace(/[\t\r\n]+/g, ' ').replace(/\\/g, '/').replace(/`/g, "'").replace(/\$\{/g, '$ {').trim();
}

const round = (n, d = 4) => Number(n.toFixed(d));

function writeModule(file, header, constName, rows) {
  const body = rows.map((r) => r.map(field).join('\t')).join('\n');
  writeFileSync(
    path.join(ROOT, file),
    `${header}\n// GENERATED by scripts/build-nav-places.mjs on ${new Date().toISOString().slice(0, 10)} — do not hand-edit.\nexport const ${constName} = \`${body}\`;\n`
  );
}

async function buildAirports() {
  const [airports, runways] = await Promise.all([fetchText(AIRPORTS_URL), fetchText(RUNWAYS_URL)]);
  const longEnough = new Set();
  for (const r of parseCsv(runways)) {
    if (r.closed === '1') continue;
    if (Number(r.length_ft) >= MIN_RUNWAY_FT) longEnough.add(r.airport_ref);
  }
  const rows = [];
  for (const a of parseCsv(airports)) {
    if (!['large_airport', 'medium_airport', 'small_airport'].includes(a.type)) continue;
    if (!longEnough.has(a.id)) continue;
    const lat = Number(a.latitude_deg);
    const lon = Number(a.longitude_deg);
    if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
    // "US-CO" reads as CO for the US and Canada; elsewhere the country code.
    const [cc, sub] = a.iso_region.split('-');
    const region = (cc === 'US' || cc === 'CA') && sub && /^[A-Z]{2}$/.test(sub) ? sub : a.iso_country;
    rows.push([a.icao_code || a.gps_code || a.ident, a.iata_code, a.name, a.municipality, region, a.iso_country, round(lat), round(lon)]);
  }
  rows.sort((x, y) => x[0].localeCompare(y[0]));
  writeModule(
    'server/src/data/airports.ts',
    '// Airports with a runway of at least 4,000 ft, for naming where a tracked\n' +
      '// aircraft took off or landed. Source: OurAirports (public domain).\n' +
      '// Row: ident \\t iata \\t name \\t municipality \\t region \\t country \\t lat \\t lon',
    'AIRPORT_ROWS',
    rows
  );
  return rows.length;
}

const norm = (s) => s.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();

function locodeCoord(s) {
  const m = /^(\d{2})(\d{2})([NS])\s+(\d{3})(\d{2})([EW])$/.exec((s || '').trim());
  if (!m) return null;
  const lat = (Number(m[1]) + Number(m[2]) / 60) * (m[3] === 'S' ? -1 : 1);
  const lon = (Number(m[4]) + Number(m[5]) / 60) * (m[6] === 'W' ? -1 : 1);
  return Math.abs(lat) <= 90 && Math.abs(lon) <= 180 ? [lat, lon] : null;
}

async function buildPorts() {
  let cities;
  try {
    cities = require('all-the-cities');
  } catch {
    throw new Error('all-the-cities is not installed: run `npm i --no-save all-the-cities@3.1.0` first');
  }
  const town = new Map();
  for (const c of cities) {
    const k = `${c.country}|${norm(c.name)}`;
    const prev = town.get(k);
    if (!prev || c.population > prev.population) town.set(k, c);
  }
  const rows = WINDSTAR_PORTS.map(([name, cc, lat, lon]) => [name, cc, '', lat, lon, 1]);
  let native = 0;
  let filled = 0;
  for (const r of parseCsv(await fetchText(LOCODE_URL))) {
    if (!r.Location || r.Change === 'X' || (r.Function || '')[0] !== '1') continue;
    let c = locodeCoord(r.Coordinates);
    if (c) native++;
    else {
      const parts = (r.NameWoDiacritics || r.Name).split(/[,/(]/).map(norm).filter(Boolean);
      const hit = parts.map((p) => town.get(`${r.Country}|${p}`)).find(Boolean);
      if (!hit) continue;
      c = [hit.loc.coordinates[1], hit.loc.coordinates[0]];
      filled++;
    }
    rows.push([r.Name, r.Country, `${r.Country}${r.Location}`, round(c[0]), round(c[1]), 0]);
  }
  writeModule(
    'server/src/data/ports.ts',
    '// Ports, for naming where a tracked ship arrived or departed. Sources:\n' +
      '// UN/LOCODE (UNECE) port locations — coordinates from GeoNames (CC BY 4.0,\n' +
      '// geonames.org) where UN/LOCODE has none — plus Windstar ports of call.\n' +
      '// Row: name \\t country \\t locode \\t lat \\t lon \\t preferred (1 = Windstar port of call)',
    'PORT_ROWS',
    rows
  );
  return { total: rows.length, native, filled, windstar: WINDSTAR_PORTS.length };
}

